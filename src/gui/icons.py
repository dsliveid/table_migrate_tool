# 默认色彩映射
DEFAULT_COLORS = {
    "primary": "#2563eb",
    "white": "#ffffff",
    "secondary": "#475569",
    "muted": "#94a3b8",
    "success": "#16a34a",
    "danger": "#dc2626",
    "warning": "#d97706",
    "info": "#0284c7",
}

# 内存图标与画板缓存
_ICON_CACHE: Dict[Tuple[str, str, int], QIcon] = {}
_PIXMAP_CACHE: Dict[Tuple[str, str, int], QPixmap] = {}


def get_svg_content(name: str, color: Optional[str] = None) -> str:
    """获取格式化后的 SVG 文本内容"""
    template = SVG_TEMPLATES.get(name)
    if not template:
        # 回退为简单圆圈
        template = """<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="2"><circle cx="12" cy="12" r="9"/></svg>"""
    
    actual_color = color or DEFAULT_COLORS.get("secondary", "#475569")
    return template.format(color=actual_color)


def get_pixmap(name: str, color: Optional[str] = None, size: int = 16) -> QPixmap:
    """渲染指定尺寸与颜色的 QPixmap"""
    actual_color = color or DEFAULT_COLORS.get("secondary", "#475569")
    cache_key = (name, actual_color, size)
    if cache_key in _PIXMAP_CACHE:
        return _PIXMAP_CACHE[cache_key]

    svg_content = get_svg_content(name, actual_color)
    renderer = QSvgRenderer(QByteArray(svg_content.encode("utf-8")))

    # 乘以设备像素比 2x 保持高分屏下极致清晰
    device_size = size * 2
    pixmap = QPixmap(device_size, device_size)
    pixmap.fill(Qt.transparent)

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.Antialiasing, True)
    painter.setRenderHint(QPainter.SmoothPixmapTransform, True)
    renderer.render(painter)
    painter.end()

    # 设置设备像素比为 2，渲染时会自动缩回逻辑 size，获得超清边缘
    pixmap.setDevicePixelRatio(2.0)

    _PIXMAP_CACHE[cache_key] = pixmap
    return pixmap


def get_icon(name: str, color: Optional[str] = None, size: int = 16) -> QIcon:
    """获取指定名称与颜色的矢量 QIcon"""
    actual_color = color or DEFAULT_COLORS.get("secondary", "#475569")
    cache_key = (name, actual_color, size)
    if cache_key in _ICON_CACHE:
        return _ICON_CACHE[cache_key]

    pix = get_pixmap(name, actual_color, size)
    icon = QIcon(pix)
    _ICON_CACHE[cache_key] = icon
    return icon


def ensure_resource_svgs():
    """将内置矢量图标自动保存至 src/gui/resources 目录，供 QSS 或打包静态资源引用"""
    try:
        res_dir = Path(__file__).resolve().parent / "resources"
        res_dir.mkdir(parents=True, exist_ok=True)
        for name, template in SVG_TEMPLATES.items():
            svg_file = res_dir / f"{name}.svg"
            if not svg_file.exists():
                svg_file.write_text(template.format(color="#64748b"), encoding="utf-8")
    except Exception:
        pass


def get_app_icon_path(extension: str = "ico") -> str:
    """获取应用程序主图标文件路径，兼顾开发与打包运行环境"""
    try:
        res_file = Path(__file__).resolve().parent / "resources" / f"app_icon.{extension}"
        if res_file.exists():
            return res_file.resolve().as_posix()
    except Exception:
        pass

    try:
        from ..core.config import AppConfig
        alt_file = AppConfig.get_base_dir() / "src" / "gui" / "resources" / f"app_icon.{extension}"
        if alt_file.exists():
            return alt_file.resolve().as_posix()
    except Exception:
        pass

    return ""


def get_app_icon() -> QIcon:
    """获取程序统一的 QIcon 实例"""
    ico_path = get_app_icon_path("ico")
    if ico_path and os.path.exists(ico_path):
        icon = QIcon(ico_path)
        if not icon.isNull():
            return icon

    png_path = get_app_icon_path("png")
    if png_path and os.path.exists(png_path):
        icon = QIcon(png_path)
        if not icon.isNull():
            return icon

    return QIcon()

